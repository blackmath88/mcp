const materials = ['K', 'P', 'W', 'M', 'D', 'G', 'R', 'Y', 'B', 'N'] as const

// One path per material: each pixel is a unit square.
const pathFor = (rows: ReadonlyArray<string>, material: string): string =>
  pipe(
    rows,
    Array.flatMap((row, y) =>
      Array.flatMap([...row], (letter, x) =>
        letter === material ? [`M${x} ${y}h1v1h-1z`] : [],
      ),
    ),
    Array.join(''),
  )

const isFill = (letter: string | undefined): boolean =>
  letter !== undefined && letter !== '.' && letter !== 'K'

// Light comes from above. A filled pixel under an edge is lit; a filled pixel
// resting on an edge is in shade. Two overlay paths give every material a
// highlight and a shadow without tripling the palette.
const shadePath = (rows: ReadonlyArray<string>, offset: -1 | 1): string =>
  pipe(
    rows,
    Array.flatMap((row, y) =>
      Array.flatMap([...row], (letter, x) =>
        isFill(letter) && !isFill(rows[y + offset]?.[x])
          ? [`M${x} ${y}h1v1h-1z`]
          : [],
      ),
    ),
    Array.join(''),
  )

export const iconView = <Message>(
  name: CapabilityName,
  h: HtmlBuilder<Message>,
): Html =>
  h.svg(
    [
      h.Class('px'),
      h.ViewBox(`0 0 ${ICON_SIZE} ${ICON_SIZE}`),
      h.ShapeRendering('crispEdges'),
      h.AriaHidden(true),
    ],
    [
      ...Array.flatMap(materials, material => {
        const d = pathFor(sprites[name], material)
        return d === '' ? [] : [h.path([h.Class(`px-${material}`), h.D(d)])]
      }),
      h.path([h.Class('px-lit'), h.D(shadePath(sprites[name], -1))]),
      h.path([h.Class('px-shade'), h.D(shadePath(sprites[name], 1))]),
    ],
  )
